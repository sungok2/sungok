package kr.openscan.scan;

import java.io.*;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.util.Locale;

/** Interoperable PLY and OBJ encoders. No Android SDK required. */
public final class ScanFileFormats {
    private ScanFileFormats() {}
    public static void writePly(File file,ScanModel.Snapshot scan) throws IOException {
        try(BufferedOutputStream out=new BufferedOutputStream(new FileOutputStream(file),131072)) {
            String header="ply\nformat binary_little_endian 1.0\ncomment generated by OpenScan 3D\n"+
                "element vertex "+scan.vertices.size()+"\n"+
                "property float x\nproperty float y\nproperty float z\n"+
                "property uchar red\nproperty uchar green\nproperty uchar blue\n"+
                "element face "+scan.triangles.size()+"\n"+
                "property list uchar int vertex_indices\nend_header\n";
            out.write(header.getBytes(StandardCharsets.US_ASCII));
            ByteBuffer buf=ByteBuffer.allocate(16*4096).order(ByteOrder.LITTLE_ENDIAN);
            for(ScanModel.Vertex v:scan.vertices) {
                if(buf.remaining()<15){out.write(buf.array(),0,buf.position());buf.clear();}
                buf.putFloat(v.x).putFloat(v.y).putFloat(v.z);
                buf.put((byte)v.r).put((byte)v.g).put((byte)v.b);
            }
            if(buf.position()>0){out.write(buf.array(),0,buf.position());buf.clear();}
            for(int[] face:scan.triangles) {
                if(buf.remaining()<13){out.write(buf.array(),0,buf.position());buf.clear();}
                buf.put((byte)3).putInt(face[0]).putInt(face[1]).putInt(face[2]);
            }
            if(buf.position()>0)out.write(buf.array(),0,buf.position());
        }
    }
    public static void writeObj(File file,ScanModel.Snapshot scan) throws IOException {
        try(BufferedWriter writer=new BufferedWriter(new OutputStreamWriter(new FileOutputStream(file),StandardCharsets.US_ASCII),131072)) {
            writer.write("# OpenScan 3D, meters, ARCore local world coords\n");
            for(ScanModel.Vertex v:scan.vertices){
                // Many tools support optional normalized RGB after xyz as a common OBJ extension.
                writer.write(String.format(Locale.US,"v %.5f %.5f %.5f %.4f %.4f %.4f\n",v.x,v.y,v.z,v.r/255f,v.g/255f,v.b/255f));
            }
            for(int[] f:scan.triangles)writer.write("f "+(f[0]+1)+" "+(f[1]+1)+" "+(f[2]+1)+"\n");
        }
    }
}
